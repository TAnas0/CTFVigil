import requests

class CTFdClient:
    """HTTP client to manage and communicate with a CTFd instance."""
    
    def __init__(self, base_url: str, token: str = None, session_cookie: str = None, csrf_token: str = None):
        self.base_url = base_url.rstrip('/')
        self.token = token
        self.session_cookie = session_cookie
        self.csrf_token = csrf_token
        
        # TODO Client must be aware of access it has, permissions, and method.
        self.session = requests.Session()
        if self.token:
            self.session.headers.update({"Authorization": f"Token {self.token}"})
        if self.session_cookie:
            self.session.cookies.set("session", self.session_cookie)
        if self.csrf_token:
            self.session.headers.update({"CSRF-Token": self.csrf_token})
            
        self.session.headers.update({
            "Content-Type": "application/json",
            "Accept": "application/json"
        })

    def is_ctfd_instance(self) -> bool:
        """Fingerprints a target URL to verify if it's running CTFd by checking the API response structure."""
        # TODO basic check of URL format
        # TODO basic liveness check?
        try:
            # /api/v1/users or /api/v1/challenges return CTFd's standard JSON wrapper even when unauthenticated
            response = self.session.get(f"{self.base_url}/api/v1/users", timeout=5)
            data = response.json()
            
            # CTFd consistently wraps responses in a JSON object containing a "success" key
            if isinstance(data, dict) and "success" in data:
                return True
        except (requests.RequestException, ValueError):
            pass
        return False

    def register_bot_user(self, username: str, email: str, password: str) -> dict:
        """Programmatically registers a bot user via CTFd's administrative API."""
        # TODO Look into automation in a celery task.
        # TODO Use an access_token generated by the administrator of CTFd
        # TODO pattern with session cookie, CSRF token, and others will be useful when the bot has created a user via browser automation
        url = f"{self.base_url}/api/v1/users"
        payload = {
            "name": username,
            "email": email,
            "password": password,
            "type": "user",
            "verified": True,  # Pre-verify so the bot can log in immediately
            "hidden": False,
            "banned": False,
            "fields": []
        }
        
        response = self.session.post(url, json=payload)
        
        # TODO properly handle rejected API requests
        # TODO format into a proper client, including the above if needed
        try:
            data = response.json()
        except ValueError:
            data = {"message": response.text}
            
        return {
            "status_code": response.status_code,
            "data": data
        }

    def get_ctfd_users(self) -> list:
        """Fetches the list of registered users from the platform."""
        # TODO properly handle rejected API requests
        try:
            response = self.session.get(f"{self.base_url}/api/v1/users", timeout=5)
            data = response.json()
            return data.get("data", []) if data.get("success") else []
        except (requests.RequestException, ValueError):
            return []

